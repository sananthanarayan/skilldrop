import json
import os
import unittest

from tests.support import load, run, workdir, write

m = load("codebase-tour", "repo_facts.py")

PACKAGE_JSON = """{
  "name": "demo",
  "main": "src/index.js",
  "scripts": {
    "build": "tsc -p .",
    "test": "jest"
  }
}
"""

MAKEFILE = """.PHONY: lint test
CC = gcc
OUT := bin
lint:
\truff check .
test: lint
\tpytest -q
"""

WORKFLOW = """name: ci
on: push
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - run: make lint
      - run: |
          pip install -e .
          # a comment
          pytest -q
      - name: done
"""

TOX = """[tox]
envlist = py39
[testenv]
commands = pytest
[testenv:lint]
commands = ruff check .
"""

NOXFILE = """import nox

@nox.session
def tests(session):
    session.install("pytest")
    session.run("pytest")
"""

PYPROJECT = """[project]
name = "demo"
[project.scripts]
demo = "demo.cli:main"
[tool.pytest.ini_options]
testpaths = ["tests"]
"""

README = """# Demo

Run `npm run build` and `npm run deploy`, then `make test` and `make release`.
Also `tox -e lint`, `tox -e docs`, `nox -s tests`, `nox -s format`.

```
$ python scripts/seed.py
$ python3 src/app.py
```

Config lives in `config/settings.yaml`, `docs/missing.md` and `src/app.py`; see https://example.invalid/x.
"""

APP = """import os

API_URL = os.environ["API_URL"]
DEBUG = os.environ.get("DEBUG")
TOKEN = os.getenv('APP_TOKEN')


def main():
    pass


if __name__ == "__main__":
    main()
"""


def build_repo(d):
    write(os.path.join(d, "package.json"), PACKAGE_JSON)
    write(os.path.join(d, "Makefile"), MAKEFILE)
    write(os.path.join(d, ".github", "workflows", "ci.yml"), WORKFLOW)
    write(os.path.join(d, "tox.ini"), TOX)
    write(os.path.join(d, "noxfile.py"), NOXFILE)
    write(os.path.join(d, "pyproject.toml"), PYPROJECT)
    write(os.path.join(d, "README.md"), README)
    write(os.path.join(d, "Dockerfile"), "FROM python:3.12\nCMD [\"python\", \"src/app.py\"]\n")
    write(os.path.join(d, "src", "app.py"), APP)
    write(os.path.join(d, "src", "index.js"), "const port = process.env.PORT || 3000;\n")
    write(os.path.join(d, "src", "gen_pb.py"), "# Code generated by protoc. DO NOT EDIT.\nX = 1\n")
    write(os.path.join(d, "tests", "test_app.py"), "def test_ok():\n    assert True\n")
    write(os.path.join(d, "tests", "test_cli.py"), "def test_ok():\n    assert True\n")
    write(os.path.join(d, "tests", "conftest.py"), "")
    write(os.path.join(d, "pkg", "server_test.go"), "package pkg\n")
    write(os.path.join(d, "vendor", "lib", "thing.py"), "import os\nos.getenv('VENDOR_ONLY')\n")
    write(os.path.join(d, "node_modules", "dep", "index.js"), "process.env.NODE_MODULES_ONLY\n")
    write(os.path.join(d, "poetry.lock"), "# lock\n")
    write(os.path.join(d, "config", "settings.yaml"), "a: 1\n")


def commands(facts, where=""):
    return {c["command"]: c for c in facts["commands"] if c["where"].startswith(where)}


class TestCollect(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls._wd = workdir()
        cls.root = cls._wd.__enter__()
        build_repo(cls.root)
        cls.facts = m.collect(cls.root)

    @classmethod
    def tearDownClass(cls):
        cls._wd.__exit__(None, None, None)

    def test_manifests_ci_and_readme_are_listed(self):
        for rel in ("package.json", "Makefile", ".github/workflows/ci.yml", "tox.ini", "noxfile.py",
                    "pyproject.toml", "README.md", "Dockerfile"):
            with self.subTest(rel=rel):
                self.assertIn(rel, self.facts["manifests"])

    def test_package_json_scripts_cite_their_line(self):
        cmds = commands(self.facts)
        self.assertEqual(cmds["npm run build"]["runs"], "tsc -p .")
        self.assertEqual(cmds["npm run build"]["where"], "package.json:5")
        self.assertEqual(cmds["npm run test"]["where"], "package.json:6")

    def test_make_targets_skip_phony_and_variables(self):
        cmds = commands(self.facts, "Makefile:")
        self.assertEqual(cmds["make lint"], {"command": "make lint", "runs": "ruff check .",
                                             "where": "Makefile:4"})
        self.assertEqual(cmds["make test"]["runs"], "pytest -q")
        self.assertEqual(sorted(cmds), ["make lint", "make test"])

    def test_ci_run_steps_single_and_block(self):
        ci = [(c["command"], c["where"]) for c in self.facts["commands"]
              if c["where"].startswith(".github/")]
        self.assertEqual(ci, [("make lint", ".github/workflows/ci.yml:7"),
                              ("pip install -e .", ".github/workflows/ci.yml:9"),
                              ("pytest -q", ".github/workflows/ci.yml:11")])

    def test_tox_envs_and_nox_sessions(self):
        cmds = commands(self.facts)
        self.assertEqual(cmds["tox -e lint"]["runs"], "ruff check .")
        self.assertEqual(cmds["tox -e lint"]["where"], "tox.ini:6")
        self.assertEqual(cmds["nox -s tests"]["runs"], 'session.run("pytest")')
        self.assertEqual(cmds["nox -s tests"]["where"], "noxfile.py:3")

    def test_pyproject_console_script_and_pytest_config(self):
        entry = [e for e in self.facts["entry_points"] if e["what"] == "console script `demo`"]
        self.assertEqual(entry, [{"what": "console script `demo`", "target": "demo.cli:main",
                                  "where": "pyproject.toml:4"}])
        self.assertEqual(commands(self.facts)["(pytest config) testpaths"]["where"], "pyproject.toml:6")

    def test_doc_commands_not_defined_anywhere(self):
        found = {(c["command"], c["why"]) for c in self.facts["doc_commands_not_found"]}
        self.assertEqual(found, {
            ("npm run deploy", "`deploy` is not defined in package.json scripts"),
            ("make release", "`release` is not defined in a Makefile"),
            ("tox -e docs", "`docs` is not defined in tox.ini"),
            ("nox -s format", "`format` is not defined in noxfile.py"),
            ("python scripts/seed.py", "`scripts/seed.py` does not exist"),
        })

    def test_doc_paths_that_do_not_exist(self):
        self.assertEqual(self.facts["doc_paths_not_found"],
                         [{"path": "docs/missing.md", "where": "README.md:11"}])

    def test_entry_points_main_guard_dockerfile_and_package_main(self):
        eps = {(e["what"], e["where"]) for e in self.facts["entry_points"]}
        self.assertIn(("main", "src/app.py:12"), eps)
        self.assertIn(("Dockerfile", "Dockerfile:2"), eps)
        self.assertIn(("package.json main", "package.json:3"), eps)

    def test_tests_grouped_by_directory_and_config(self):
        self.assertEqual(self.facts["tests"], {"pkg": 1, "tests": 2})
        self.assertEqual(self.facts["test_config"], ["tests/conftest.py"])

    def test_generated_marker_in_first_lines(self):
        self.assertEqual([(g["path"], g["where"]) for g in self.facts["generated"]],
                         [("src/gen_pb.py", "src/gen_pb.py:1")])

    def test_vendored_dirs_and_lockfiles(self):
        self.assertEqual(self.facts["vendored"], ["vendor"])
        self.assertEqual(self.facts["lockfiles"], ["poetry.lock"])

    def test_env_vars_with_line_and_skipped_dirs_ignored(self):
        env = sorted((e["name"], e["where"]) for e in self.facts["env_vars"])
        self.assertEqual(env, [("API_URL", "src/app.py:3"), ("APP_TOKEN", "src/app.py:5"),
                               ("DEBUG", "src/app.py:4"), ("PORT", "src/index.js:1")])

    def test_largest_dirs_counts_files(self):
        dirs = {d["dir"]: d["files"] for d in self.facts["largest_dirs"]}
        self.assertEqual(dirs["src"], 3)
        self.assertEqual(dirs["tests"], 3)
        self.assertNotIn("node_modules", dirs)


class TestDocChecks(unittest.TestCase):
    def test_bare_make_with_no_makefile_is_reported(self):
        with workdir() as d:
            write(os.path.join(d, "README.md"), "Build with `make`.\n")
            facts = m.collect(d)
        self.assertEqual(facts["doc_commands_not_found"],
                         [{"command": "make", "where": "README.md:1",
                           "why": "no make file defines any target"}])

    def test_npm_install_and_yarn_add_are_not_flagged(self):
        with workdir() as d:
            write(os.path.join(d, "README.md"), "Run `npm install`, `npm ci` and `yarn add left-pad`.\n")
            facts = m.collect(d)
        self.assertEqual(facts["doc_commands_not_found"], [])

    def test_yarn_and_pnpm_targets_check_package_scripts(self):
        with workdir() as d:
            write(os.path.join(d, "package.json"), '{"scripts": {"lint": "eslint ."}}\n')
            write(os.path.join(d, "README.md"), "`yarn lint`, `pnpm run lint`, `yarn deploy`\n")
            facts = m.collect(d)
        self.assertEqual([c["command"] for c in facts["doc_commands_not_found"]], ["yarn deploy"])

    def test_gitlab_script_items(self):
        with workdir() as d:
            write(os.path.join(d, ".gitlab-ci.yml"),
                  "test:\n  script:\n    - make test\n    - 'pytest -q'\n  stage: test\n")
            facts = m.collect(d)
        self.assertEqual([(c["command"], c["where"]) for c in facts["commands"]],
                         [("make test", ".gitlab-ci.yml:3"), ("pytest -q", ".gitlab-ci.yml:4")])

    # BUG: tox's multi-line `commands =` (value on the following indented lines) is recorded with runs "".
    @unittest.expectedFailure
    def test_tox_multiline_commands_are_captured(self):
        with workdir() as d:
            write(os.path.join(d, "tox.ini"), "[testenv:unit]\ncommands =\n    pytest -q\n")
            facts = m.collect(d)
        self.assertIn("pytest -q", facts["commands"][0]["runs"])

    def test_gitattributes_generated_entries(self):
        with workdir() as d:
            write(os.path.join(d, ".gitattributes"), "api/*.pb.go linguist-generated=true\n")
            facts = m.collect(d)
        self.assertEqual(facts["generated"][0]["path"], "api/*.pb.go")
        self.assertEqual(facts["generated"][0]["where"], ".gitattributes:1")

    def test_empty_repo_has_empty_facts(self):
        with workdir() as d:
            facts = m.collect(d)
        self.assertEqual(facts["commands"], [])
        self.assertEqual(facts["manifests"], [])
        self.assertEqual(facts["tests"], {})
        self.assertEqual(facts["largest_dirs"], [])


class TestCli(unittest.TestCase):
    def test_json_output_matches_collect(self):
        with workdir() as d:
            build_repo(d)
            code, out, _ = run("codebase-tour", "repo_facts.py", d, "--json")
            expected = m.collect(d)
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(out), expected)

    def test_markdown_output_has_sections_and_citations(self):
        with workdir() as d:
            build_repo(d)
            code, out, _ = run("codebase-tour", "repo_facts.py", d)
        self.assertEqual(code, 0)
        self.assertIn("# Repository facts", out)
        self.assertIn("## Commands the docs name that nothing defines", out)
        self.assertIn("`make lint` → `ruff check .` — Makefile:4", out)
        self.assertIn("`API_URL` — src/app.py:3", out)

    def test_max_caps_items_per_section(self):
        with workdir() as d:
            build_repo(d)
            code, out, _ = run("codebase-tour", "repo_facts.py", d, "--max", "1")
        self.assertEqual(code, 0)
        self.assertIn("- ... 3 more (raise --max to see them)", out)  # 4 env vars, 1 shown
        self.assertNotIn("`DEBUG` — src/app.py:4", out)

    def test_empty_repo_markdown_says_none_found(self):
        with workdir() as d:
            code, out, _ = run("codebase-tour", "repo_facts.py", d)
        self.assertEqual(code, 0)
        self.assertIn("- none found: no package scripts", out)
        self.assertIn("- no test files found", out)

    def test_missing_root_exits_2_with_message(self):
        with workdir() as d:
            code, _, err = run("codebase-tour", "repo_facts.py", os.path.join(d, "nope"))
        self.assertEqual(code, 2)
        self.assertIn("is not a directory", err)
        self.assertNotIn("Traceback", err)

    def test_is_read_only(self):
        with workdir() as d:
            build_repo(d)
            before = sorted(os.path.join(p, f) for p, _, fs in os.walk(d) for f in fs)
            run("codebase-tour", "repo_facts.py", d)
            run("codebase-tour", "repo_facts.py", d, "--json")
            after = sorted(os.path.join(p, f) for p, _, fs in os.walk(d) for f in fs)
        self.assertEqual(before, after)


if __name__ == "__main__":
    unittest.main()
